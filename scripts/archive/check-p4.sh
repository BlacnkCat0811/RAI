#!/usr/bin/env bash
# Invoked inside apps/server by the disposable fnOS test runner.
set -euo pipefail
[[ -z "$(gofmt -l .)" ]]
go mod verify
go test -count=1 -json ./... > /tmp/rai-p4-unit-$$.json
python3 -c 'import json,sys; x=[json.loads(s) for s in open(sys.argv[1])];print("P4_UNIT_PASSES="+str(sum(e.get("Action")=="pass" and "Test" in e for e in x)))' /tmp/rai-p4-unit-$$.json
rm /tmp/rai-p4-unit-$$.json
go test -race -count=1 ./...
go vet ./...
go build ./...
python3 ../../scripts/check-boundaries.py
go test -race -count=1 -tags=integration -p 1 -timeout=30m ./...
go vet -tags=integration,scale ./...
echo 'P4_GO_GATES=PASS'
